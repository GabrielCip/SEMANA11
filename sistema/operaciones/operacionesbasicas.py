def sumar(x,y):
    sumado = x + y
    return sumado

def restar(x,y):
    restado = x - y
    return restado    

def multiplicar(x,y):
    multiplicado = x * y
    return multiplicado

def dividir(x,y):
    dividido = x / y
    return dividido

def potenciar(x,y):
    potenciado = x ** y
    return potenciado

def residuo(x,y):
    resid = x % y
    return resid